def test_parse_ticker_text_normalizes_and_deduplicates():
    assert parse_ticker_text("nvda, amd\nNVDA msft") == ["NVDA", "AMD", "MSFT"]


def test_load_universe_has_future_score_columns():
    universe = load_universe(Path("data/universe_smh.csv"))
    assert {"symbol", "fundamental_score", "catalyst_score", "notes"}.issubset(universe.columns)
    assert "NVDA" in set(universe["symbol"])


@pytest.mark.parametrize("path,expected_symbols", EXPECTED_SEED_SYMBOLS.items())
def test_seed_universe_files_have_expected_symbols(path: Path, expected_symbols: set[str]):
    universe = load_universe(path)

    assert list(universe.columns) == UNIVERSE_COLUMNS
    assert len(universe) == len(expected_symbols)
    assert not universe["symbol"].duplicated().any()
    assert universe["theme"].astype(str).str.strip().ne("").all()
    assert set(universe["symbol"]) == expected_symbols


def test_merge_manual_tickers_adds_missing_symbols():
    universe = load_universe(Path("data/universe_smh.csv")).head(1)
    merged = merge_manual_tickers(universe, ["NVDA", "TSLA"])
    assert "TSLA" in set(merged["symbol"])
    assert merged.loc[merged["symbol"] == "TSLA", "theme"].iloc[0] == "Manual"
